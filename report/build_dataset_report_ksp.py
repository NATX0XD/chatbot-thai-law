def th(n) -> str:
    """Arabic digits to Thai, with thousands separators kept."""
    return f"{n:,}".translate(THAI_DIGITS) if isinstance(n, int) else str(n).translate(THAI_DIGITS)


def load():
    with open(CORPUS, encoding="utf-8") as fh:
        return [json.loads(line) for line in fh if line.strip()]


def by_doc(records):
    out = {}
    for r in records:
        out.setdefault(r["sysid"], []).append(r)
    missing = set(out) - set(ORDER)
    if missing:
        raise SystemExit(
            "corpus has documents this report does not know how to present: "
            + ", ".join(sorted(missing)) + " -- add them to ORDER and ROLE")
    return out


def sec_key(r):
    """Sort key for a section number: 17/1 sorts after 17 and before 18."""
    head, _, tail = r["section"].partition("/")
    return (int(re.sub(r"\D", "", head) or 0), int(tail or 0), r["part"])


def audit_body() -> str:
    """The audit report without its own title, so it nests under a chapter here."""
    with open(AUDIT, encoding="utf-8") as fh:
        lines = fh.read().splitlines()
    lines = [ln for ln in lines if not ln.startswith("# ")]
    # its "## " headings become "### " one level down
    return "\n".join("#" + ln if ln.startswith("## ") else ln for ln in lines).strip()


def read_methods() -> dict:
    """Which reader each document needed, taken from the audit table."""
    out = {}
    with open(AUDIT, encoding="utf-8") as fh:
        for line in fh:
            m = re.match(r"\|\s*`([a-z0-9-]+)`\s*\|", line)
            if m:
                out[m.group(1)] = line.rstrip().rstrip("|").rsplit("|", 1)[1].strip()
    return out


def sources() -> dict:
    """sysid -> (sha256, url, label) straight out of the fetch script."""
    with open(FETCH, encoding="utf-8") as fh:
        body = fh.read()
    rows = re.findall(r'^"([a-z0-9-]+)\|([0-9a-f]{64})\|(\S+)\|(.+)"$', body, re.M)
    if len(rows) != len(ORDER):
        raise SystemExit(f"fetch_ksp.sh lists {len(rows)} documents, corpus has {len(ORDER)}")
    return {key: (sha, url, label) for key, sha, url, label in rows}


