def estimate_pages(md: str) -> int:
    """Rendered pages, counted in lines rather than characters.

    A heading, a table row and a short paragraph each take a whole line however
    few characters are in them, and "---" forces a new page. Counting characters
    and dividing ignores all three and lands about ten per cent short.
    """
    lines = 0
    pages = 0
    for block in md.split("\n\n"):
        block = block.strip()
        if not block:
            continue
        if block == "---":
            pages += 1 if lines else 0
            lines = 0
            continue
        for ln in block.splitlines():
            if ln.startswith("|") or ln.startswith("#"):
                lines += 1
            else:
                lines += max(1, -(-len(ln) // CHARS_PER_LINE))
        # Word's default spacing after a paragraph is 8 pt -- half a 16 pt line,
        # not a whole one.
        lines += 0.5
        while lines >= LINES_PER_PAGE:
            lines -= LINES_PER_PAGE
            pages += 1
    return pages + (1 if lines else 0)


